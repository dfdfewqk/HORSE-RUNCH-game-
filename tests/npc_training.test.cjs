'use strict';
const assert=require('node:assert/strict');
const T=require('../systems/npc-training.js');
const F=require('../systems/foal-education.js');
function h(id,s=60,cap=95){return{id,age:3,retired:false,condition:96,fatigue:0,genetic:{speed:cap,stamina:cap,power:cap},caps:{speed:cap,stamina:cap,power:cap},speed:s,stamina:s,power:s,growthFoundation:{growthEfficiency:1},rating:70};}
function ranch(name, horses){return{name,named:true,horses};}
const player=h(1,70,92),strong=ranch('그랜드 스터드',[h(4,80,94),h(5,80,94)]),red=ranch('레드크라운 목장',[h(6,63,90)]),generic={name:'일반 목장',horses:[h(7,60,90)]};
strong.horses.forEach(q=>q.rating=93);
const state={year:1,month:1,day:1,horses:[player],npcs:[strong,red,generic]};
const beforePlayer=JSON.stringify(player),beforeGeneric=JSON.stringify(generic);
const store=T.ensure(state);
assert.equal(store.lastMonth,'1-1');
assert.equal(store.ranches['그랜드 스터드'].sessions,1,'top ranch slowed');
assert.equal(store.ranches['레드크라운 목장'].sessions,4,'same era wealthy rival responds to player');
assert.equal(T.advance(state,F.trainingGain).applied,false,'no backfill on load');
state.day=1;state.month=2;
const result=T.advance(state,F.trainingGain);
assert.equal(result.applied,true);
assert.equal(result.review,false);
assert.equal(result.summaries.length,2);
assert.equal(result.summaries[0].sessions,2);
assert.ok(result.summaries[0].gains>=0);
assert.deepEqual(JSON.stringify(player),beforePlayer,'never train player');
assert.deepEqual(JSON.stringify(generic),beforeGeneric,'non-named farm untouched');
assert.equal(T.advance(state,F.trainingGain).applied,false,'no double training in same month');
assert.equal(store.ranches['그랜드 스터드'].last.month,'1-2');
state.month=3;T.advance(state,F.trainingGain);
assert.equal(store.lastQuarter,'1-Q1');
player.rating=92;
state.month=4;const qResult=T.advance(state,F.trainingGain);
assert.equal(qResult.review,true,'review every three months');
assert.equal(store.lastQuarter,'1-Q2');
assert.equal(store.ranches['그랜드 스터드'].sessions,3,'catch-up increases training attempts, not stat grants');
assert.equal(store.ranches['그랜드 스터드'].mode,'투자 확대');
assert.ok(result.summaries.every(x=>x.estimatedCost===x.sessions*75000));
assert.ok([...strong.horses,...red.horses].every(x=>T.STATS.every(k=>x[k]<=x.caps[k])),'cap is absolute');
const fresh=JSON.parse(JSON.stringify(state));
const a=T.ensure(fresh);
assert.equal(a.lastMonth,'1-4');
assert.equal(T.advance(fresh,F.trainingGain).applied,false,'save reload idempotent');
assert.equal(a.ranches['그랜드 스터드'].focus,store.ranches['그랜드 스터드'].focus);
assert.equal(strong.horses.length,2);
assert.equal(red.horses.length,1);
console.log('HORSE RANCH 20.6 NPC monthly training & quarterly reviews: OK');
