'use strict';
const assert=require('node:assert/strict');
const L=require('../systems/horse-lifespan.js');
function horse(id,age=10,overrides={}){
 return {id,name:'말'+id,age,gender:'수',retired:age>12,parents:{sire:'아버지',dam:'어머니'},fatherId:'anc-a',motherId:'anc-b',distanceBand:'마일',coat:'black',starts:10,wins:3,seconds:2,thirds:1,history:[{year:5,month:6,day:24,grade:'G1',place:1,dist:2000}],careerAchievements:{majorWins:[{year:5,month:6,day:24,grade:'G1',dist:2000}],peakRating:95},...overrides};
}
// Rough population mean in the user-selected 22~30 range, with genuinely rare 30+ survivors.
const targets=Array.from({length:10000},(_,i)=>L.targetAge(horse(1000+i,0)));
const avg=targets.reduce((sum,x)=>sum+x,0)/targets.length;
const long=targets.filter(x=>x>30).length/targets.length;
assert.ok(avg>=22&&avg<=30,'average lifespan within user range: '+avg);
assert.ok(long>.025&&long<.15,'rare 30+ lifespan proportion '+long);
assert.ok(targets.some(x=>x>=35),'some 35+ year survivors');
assert.ok(targets.every(x=>x>=19&&x<=36));
assert.equal(L.targetAge(horse(44)),L.targetAge(horse(44)),'deterministic lifetime');
const elder=horse(77,35);L.ensureHorse(elder);
assert.ok(elder.lifeSpan.targetAge>=36,'pre-existing elderly horse not deleted on upgrade');
const veteran=horse(5,25,{lifeSpan:{version:1,targetAge:26},retired:true});
const other=horse(6,25,{lifeSpan:{version:1,targetAge:32}});
const foal=horse(7,26,{lifeSpan:{version:1,targetAge:26},gender:'암'});
const parent=horse(8,26,{lifeSpan:{version:1,targetAge:26}});
const world={year:1,ranchName:'우리목장',horses:[veteran,foal,parent],npcs:[{name:'레드크라운 목장',horses:[other]}],registrations:[{horseId:5}],selectedHorse:5,pedigreeArchive:[{id:'anc-a',name:'조상'}],horseLifeEvents:[],breedings:[{mareId:7,sireId:8,due:999}],horseLifespanClock:{version:1,lastYear:1,totalDeaths:0}};
L.ensureWorld(world);
assert.equal(L.advanceYear(world).applied,false,'no death upon loading same year');
world.year=2;for(const h of world.horses)h.age++;world.npcs[0].horses[0].age++;
const result=L.advanceYear(world,{getTitle:h=>h.id===5?'G1 1승':null});
assert.equal(result.applied,true);
assert.equal(result.deaths,1,'pending breeding keeps both mare and sire alive');
assert.equal(result.deferred,2);
assert.equal(result.playerDeaths,1);
assert.equal(world.horses.length,2);
assert.equal(world.npcs[0].horses[0].id,6);
assert.equal(world.selectedHorse,null);
assert.equal(world.registrations.length,0);
const archived=world.pedigreeArchive.find(h=>h.id===5);
assert.equal(archived.name,'말5');
assert.equal(archived.deceased,true);
assert.equal(archived.fatherId,'anc-a');
assert.equal(archived.careerAchievements.majorWins[0].grade,'G1');
assert.equal(archived.careerAchievements.peakRating,95);
assert.equal(world.horseLifeEvents.length,1);
assert.equal(L.advanceYear(world).applied,false,'no double processing');
assert.equal(world.horseLifeEvents.length,1);
assert.equal(world.horseLifespanClock.totalDeaths,1);
world.breedings=[];
world.year=3;
const outcome=L.advanceYear(world);
assert.equal(outcome.deaths,2,'pending animals can naturally depart after birth is resolved');
assert.equal(world.horses.length,0);
assert.equal(world.npcs[0].horses.length,1);
assert.equal(world.pedigreeArchive.filter(h=>h.deceased).length,3);
const reopened=JSON.parse(JSON.stringify(world));
assert.equal(L.advanceYear(reopened).applied,false,'saved game remains idempotent');
assert.equal(reopened.horseLifespanClock.totalDeaths,3);
assert.equal(L.ensureHorse(reopened.pedigreeArchive[1]).targetAge>0,true);
console.log('HORSE RANCH 20.9 longevity and lineage records OK',JSON.stringify({average:avg,longRate:long}));
