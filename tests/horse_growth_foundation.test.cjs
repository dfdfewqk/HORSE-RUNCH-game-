'use strict';
const assert=require('node:assert/strict');
const growth=require('../systems/horse-growth-foundation.js');
const seed={id:12,name:'새벽바람',age:0,speed:45,stamina:52,power:48};
const fresh=growth.createProfile(seed);
assert.equal(fresh.baselineSource,'birth');
assert.deepEqual(fresh.baseStats,{speed:45,stamina:52,power:48});
assert.ok(fresh.growthEfficiency>=.85&&fresh.growthEfficiency<=1.15);
assert.equal(fresh.innateTemperament,growth.createProfile(seed).innateTemperament);
assert.equal(fresh.growthEfficiency,growth.createProfile(seed).growthEfficiency);
const adult=growth.createProfile({...seed,age:3});
assert.equal(adult.baselineSource,'generated');
const legacy={id:81,name:'기존말',age:5,speed:87,stamina:70,power:65,genetic:{speed:94},caps:{speed:95},profileTraits:{temperament:'침착'}};
growth.ensureProfile(legacy);
assert.equal(legacy.growthFoundation.baselineSource,'legacy-snapshot');
assert.deepEqual(legacy.growthFoundation.baseStats,{speed:87,stamina:70,power:65});
assert.equal(legacy.growthFoundation.growthEfficiency,null);
assert.equal(legacy.growthFoundation.innateTemperament,'침착');
legacy.speed=90;
growth.ensureProfile(legacy);
assert.equal(legacy.growthFoundation.baseStats.speed,87,'baseline must not change after training');
assert.equal(legacy.speed,90,'actual stats must not be modified');
assert.equal(legacy.genetic.speed,94,'genetics must not be modified');
assert.equal(legacy.caps.speed,95,'caps must not be modified');
assert.deepEqual(growth.ensureProfile(JSON.parse(JSON.stringify(legacy))).growthFoundation,legacy.growthFoundation,'save reload stable');
const noRecord={id:92,name:'미확인',age:4,speed:61,stamina:63,power:62};
growth.ensureProfile(noRecord);
assert.equal(noRecord.growthFoundation.innateTemperament,null,'unknown legacy personality must not be invented');
assert.equal(noRecord.growthFoundation.growthEfficiency,null);
console.log('HORSE RANCH 20.3 growth foundation: OK');
