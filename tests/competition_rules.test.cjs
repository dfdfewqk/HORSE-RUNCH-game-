'use strict';
const assert=require('node:assert/strict');
const R=require('../systems/competition-rules.js');
const rookie={id:1,speed:70,stamina:70,power:70,starts:0,wins:0,rating:null};
assert.equal(R.initialRating(rookie),59);
assert.equal(R.rating(rookie),59);
assert.equal(R.entryCheck(rookie,{grade:'G1'}).ok,false);
assert.equal(R.entryCheck(rookie,{grade:'일반'}).ok,true);
assert.equal(R.entryCheck({...rookie,rating:82},{grade:'G1'}).ok,true);
assert.equal(R.entryCheck({...rookie,rating:73},{grade:'G2'}).ok,false);
assert.equal(R.entryCheck({...rookie,rating:74},{grade:'G2'}).ok,true);
assert.equal(R.newRating(70,'G1',1,12),77);
assert.equal(R.newRating(70,'G1',12,12),68);
assert.equal(R.newRating(109,'G1',1,12),110);
assert.equal(R.ratingDelta('일반',1,12),5);
assert.equal(R.ratingDelta('일반',12,12),-2);
const races=[{year:1,month:3,day:24,no:2,grade:'일반',state:'open'},{year:1,month:3,day:24,no:3,grade:'G1',state:'open'},{year:1,month:6,day:24,no:2,grade:'미승리',state:'finished'}];
R.g2Schedule(races);
assert.equal(races[0].grade,'G2');
assert.equal(races[0].prize,35000000);
assert.equal(races[1].grade,'G1');
assert.equal(races[2].grade,'미승리','finished races must not change');
const r={id:'race-1',dist:1600,surface:'잔디'};
assert.equal(R.entrantScore({...rookie,distanceBand:'마일',surface:'잔디'},r,59),R.entrantScore({...rookie,distanceBand:'마일',surface:'잔디'},r,59),'deterministic choice');
