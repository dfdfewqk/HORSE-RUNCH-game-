'use strict';
const assert=require('node:assert/strict');
const N=require('../systems/npc-auto-racing.js');
const engine=require('../systems/race-engine.js');
const C=require('../systems/competition-rules.js');
const R=require('../systems/ranch-ranking.js');
const mk=(id,v=81)=>({id,name:'경주마 '+id,age:4,retired:false,injury:0,condition:85,fatigue:5,hoof:93,speed:v,stamina:v,power:v,genetic:{speed:90},caps:{speed:95},rating:80,starts:0,wins:0,seconds:0,thirds:0,lastRaceIndex:-99,history:[],distanceBand:'마일',surface:'잔디',style:'선행'});
const horses=Array.from({length:14},(_,i)=>mk(100+i));
const player=mk(1,94),world={year:1,month:1,day:10,ranchName:'나의 목장',money:123400,stalls:8,horses:[player],npcs:[{name:'A목장',horses:horses.slice(0,7)},{name:'B목장',horses:horses.slice(7)}],races:[{id:'1-1-10-1',year:1,month:1,day:10,grade:'일반',dist:1600,surface:'잔디',state:'open'},{id:'1-1-10-2',year:1,month:1,day:10,grade:'G3',dist:1600,surface:'잔디',state:'open'},{id:'1-1-10-3',year:1,month:1,day:10,grade:'G1',dist:1600,surface:'잔디',state:'open'}],results:[],registrations:[],reputation:31};
let recorded=0,achievements=0;
const ctx={eligible:(h,r)=>!h.retired&&h.age>=2&&(h.lastRaceIndex<0||N.dayOf(r)-h.lastRaceIndex>=8)&&C.entryCheck(h,r).ok,score:C.entrantScore,simulate:engine.simulate,rating:C.rating,newRating:C.newRating,recordAchievement:()=>{achievements++;},recordMerit:(w,r)=>{recorded+=R.recordRace(w,r).added;}};
const save=JSON.stringify({money:world.money,player,results:world.results,registrations:world.registrations,reputation:world.reputation});
assert.equal(N.dayOf(world),10);
assert.equal(N.ensure(world).totalRaces,0);
const outcome=N.closeDay(world,10,ctx);
assert.equal(outcome.applied,true);
assert.ok(outcome.held>=1);
assert.equal(outcome.held+outcome.cancelled,3);
assert.equal(world.races.every(r=>r.state==='finished'),true);
assert.equal(world.races.filter(r=>r.result.length>0).every(r=>r.result.every(row=>row.horseId!==player.id)),true);
const raceIds=world.races.flatMap(r=>r.result.map(row=>row.horseId));
assert.equal(new Set(raceIds).size,raceIds.length,'one horse must not run twice the same day');
assert.equal(JSON.stringify({money:world.money,player,results:world.results,registrations:world.registrations,reputation:world.reputation}),save,'player state remains untouched');
assert.ok(recorded>=2);
assert.ok(achievements>=2);
assert.equal(N.closeDay(world,10,ctx).applied,false,'no duplicate settlement');
assert.equal(N.ensure(world).totalRaces,outcome.held);
assert.ok(world.npcAutoRacing.history.length===3);
for(const r of world.races)if(r.result.length){assert.ok(r.ratingSettled);assert.ok(r.ratingChanges.length===r.result.length);}
const clone=JSON.parse(JSON.stringify(world));assert.equal(N.ensure(clone).totalRaces,outcome.held);assert.equal(N.closeDay(clone,10,ctx).applied,false);
const before=horses[0].fatigue;N.restoreNpcDaily(world);assert.equal(horses[0].fatigue,Math.max(0,before-3));
assert.equal(player.fatigue,5,'NPC recovery must never touch player');
console.log('NPC_AUTO_RACING_TEST_PASS',JSON.stringify({held:outcome.held,cancelled:outcome.cancelled,rankEvents:recorded}));
